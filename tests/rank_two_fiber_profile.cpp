AlgebraicRootCertificate readRoot(std::istream& in){
    AlgebraicRootCertificate c;int n=0;in>>n;require(n>=2&&n<=257,"invalid actual polynomial degree");
    for(int k=0;k<n;++k){std::string s;in>>s;require(!s.empty(),"truncated actual polynomial");c.coefficients.push_back(s);}
    in>>c.rootIndex>>c.lower>>c.upper>>c.rootIdentity;require(bool(in),"truncated actual certificate");return c;
}
P readPolynomial(const std::string& record){
    const P x=CGAL::shift(P(1),1,0),y=CGAL::shift(P(1),1,1);P f(0);std::istringstream in(record);std::string term;
    while(std::getline(in,term,';')){const auto comma=term.find(','),colon=term.find(':');
        require(comma!=std::string::npos&&colon!=std::string::npos,"invalid actual supporting polynomial");
        const int i=std::stoi(term.substr(0,comma)),j=std::stoi(term.substr(comma+1,colon-comma-1));
        require(i>=0&&i<=4&&j>=0&&j<=4,"support degree outside actual arrangement contract");
        f+=P(CORE::BigInt(term.substr(colon+1)))*CGAL::ipower(x,i)*CGAL::ipower(y,j);}
    require(!CGAL::is_zero(f),"zero actual curve");return f;
}
